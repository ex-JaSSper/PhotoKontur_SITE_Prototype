// Цвет рубрики: общий для журнала на главной, ленты блога и страницы статьи.
export const categoryTone: Record<string, 'steel' | 'orange' | 'sky'> = { 'Процесс': 'steel', 'Управление': 'orange', 'Продукт': 'sky' };
export const toneOf = (category: string) => categoryTone[category] ?? 'steel';
// Атмосферное фото можно кадрировать; скриншоты продукта показываем целиком.
export const isPhotoCover = (a: Article) => a.cover === '/media/studio.webp';

// Мини-разметка текста блоков: экранирование, затем ссылки и выделение.
export function inline(text: string): string {
  const esc = text.replace(/[&<>"]/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;' }[c]!));
  return esc
    .replace(/\[([^\]]+)\]\((\/[^)\s]*)\)/g, '<a href="$2">$1</a>')
    .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>');
}
